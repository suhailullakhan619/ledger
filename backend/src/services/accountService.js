const accounts = require('../repositories/accountRepository');
const transactions = require('../repositories/transactionRepository');
const { AccountNotFoundError } = require('../errors');
const { serializeAccount, serializeTransaction, paginationMeta } = require('./serializers');
const { toMajorUnits } = require('../utils/money');

async function getAccountOrThrow(id, session) {
  const account = await accounts.findById(id, session);
  if (!account) throw new AccountNotFoundError(id);
  return account;
}

module.exports = {
  getAccountOrThrow,

  async createAccount({ name }) {
    // id, balance and created_at are always generated by the system.
    return serializeAccount(await accounts.create({ name }));
  },

  async listAccounts({ page, limit }) {
    const { total, rows } = await accounts.findPage({ limit, offset: (page - 1) * limit });
    return { data: rows.map(serializeAccount), pagination: paginationMeta({ page, limit, total }) };
  },

  async getAccount(id) {
    return serializeAccount(await getAccountOrThrow(id));
  },

  async getBalance(id) {
    const account = await getAccountOrThrow(id);
    return { account_id: String(account._id), balance: toMajorUnits(account.balance) };
  },

  async getStats() {
    const [accountSummary, txnSummary, recent] = await Promise.all([
      accounts.summary(),
      transactions.summary(),
      transactions.recent(8),
    ]);
    return {
      total_accounts: accountSummary.total_accounts,
      total_balance: toMajorUnits(accountSummary.total_balance),
      transactions: {
        total: txnSummary.credit.count + txnSummary.debit.count,
        credit_count: txnSummary.credit.count,
        debit_count: txnSummary.debit.count,
        credit_volume: toMajorUnits(txnSummary.credit.volume),
        debit_volume: toMajorUnits(txnSummary.debit.volume),
      },
      recent_transactions: recent.map(serializeTransaction),
    };
  },
};
